async function migrateLegacyLocalStorageIfNeeded(): Promise<void> {
  const raw = localStorage.getItem(MIGRATION_KEY);
  if (!raw) return;
  try {
    const old = JSON.parse(raw) as DailyLog[];
    for (const item of old) {
      await putDailyLog(item);
    }
    localStorage.removeItem(MIGRATION_KEY);
  } catch {
    // ignore bad legacy payload
  }
}

function inferMood(summary: DailyLog["summary"]): DailyLog["journal"]["mood"] {
  if (summary.levelUp || summary.totalXP >= 260) return "excited";
  if (summary.totalTasks >= 4) return "productive";
  if (summary.totalTasks <= 1 && summary.totalXP < 40) return "tired";
  return "peaceful";
}

function calculatePower(stats: DailyLog["snapshot"]["stats"]): number {
  return Math.round(stats.str * 1.2 + stats.int * 1.2 + stats.agi + stats.cha + stats.con * 1.3);
}

export function generateDailyJournal(log: DailyLog): string {
  const parts: string[] = [];
  parts.push(`📅 ${log.date} 冒险日志\n`);
  parts.push(`今日等级：Lv.${log.snapshot.level} | 战力评估：${calculatePower(log.snapshot.stats)}\n`);

  if (log.summary.totalTasks === 0) {
    parts.push("今日在城镇休息，为明日养精蓄锐。\n");
  } else {
    parts.push(
      `今日出征${log.summary.totalTasks}次，斩获${log.summary.totalXP}XP，${log.summary.totalCrystals}晶石。\n`
    );
  }

  if (log.summary.levelUp) {
    parts.push("🎉 恭喜升级！今日实力获得质的飞跃！\n");
  }

  const topAdventures = log.adventures
    .filter((a) => a.result === "victory")
    .sort((a, b) => b.rewards.xp - a.rewards.xp)
    .slice(0, 3);

  if (topAdventures.length > 0) {
    parts.push("\n⚔️ 精彩战役：\n");
    topAdventures.forEach((adv, i) => {
      parts.push(
        `${i + 1}. 在${adv.location}遭遇${adv.monsterName}，${adv.highlights.join("，")}，${adv.duration}分钟苦战后取得胜利，获得${
          adv.rewards.drops.join("、") || "战利品若干"
        }。\n`
      );
    });
  }

  if (log.checkIns.length > 0) {
    parts.push(`\n📸 今日留下了${log.checkIns.length}个高光时刻。\n`);
    log.checkIns.slice(0, 6).forEach((ci, i) => {
      if (ci.type === "text") parts.push(`  时刻${i + 1}：${ci.content.substring(0, 30)}...\n`);
      else if (ci.type === "image") parts.push(`  时刻${i + 1}：[图片记录]\n`);
      else parts.push(`  时刻${i + 1}：[语音记录]\n`);
    });
  }

  parts.push("\n💪 属性变化：");
  parts.push(
    `力量${log.snapshot.stats.str} | 智力${log.snapshot.stats.int} | 敏捷${log.snapshot.stats.agi} | 魅力${log.snapshot.stats.cha} | 体质${log.snapshot.stats.con}`
  );
  return parts.join("");
}

function difficultyToRecord(d: Task["difficulty"]): AdventureRecord["difficulty"] {
  if (d === "Hard") return "hard";
  if (d === "Normal") return "medium";
  return "easy";
}

export async function appendDailyAdventureLog(input: {
  completedAt: string;
  task: Task;
  actualDuration: number;
  finalXp: number;
  finalCrystals: number;
  raceBonusTags: string[];
  levelUp: boolean;
  unlockedSkills: string[];
  droppedEquipmentIds: string[];
  adventureMeta: {
    monsterName?: string;
    location?: string;
    highlights: string[];
    result: "victory" | "retreat";
    drops: string[];
  };
  profileAfterCompletion: UserProfile | null;
  profileXpAfterCompletion: number;
}): Promise<void> {
  const date = ymd(input.completedAt);
  const existing = await getDailyLogByDate(date);
  const base: DailyLog =
    existing
      ? existing
      : {
          date,
          summary: {
            totalTasks: 0,
            totalXP: 0,
            totalCrystals: 0,
            raceBonusTriggered: [],
            levelUp: false,
            newSkillsUnlocked: [],
            equipmentAcquired: []
          },
          adventures: [],
          checkIns: [],
          journal: {
            autoGenerated: "",
            mood: "peaceful"
          },
          snapshot: {
            level: 1,
            stats: { str: 0, int: 0, agi: 0, cha: 0, con: 0 },
            equipment: {}
          }
        };

  base.adventures.push({
    taskId: input.task.id,
    taskName: input.task.title,
    profession: input.task.profession,
    difficulty: difficultyToRecord(input.task.difficulty),
    monsterName: input.adventureMeta.monsterName ?? "未知魔物",
    location: input.adventureMeta.location ?? "未知区域",
    duration: input.actualDuration,
    result: input.adventureMeta.result,
    rewards: {
      xp: input.finalXp,
      crystals: input.finalCrystals,
      drops: input.adventureMeta.drops
    },
    highlights: input.adventureMeta.highlights
  });

  base.summary.totalTasks += 1;
  base.summary.totalXP += input.finalXp;
  base.summary.totalCrystals += input.finalCrystals;
  base.summary.levelUp = base.summary.levelUp || input.levelUp;
  for (const tag of input.raceBonusTags) {
    if (!base.summary.raceBonusTriggered.includes(tag)) base.summary.raceBonusTriggered.push(tag);
  }
  for (const node of input.unlockedSkills) {
    if (!base.summary.newSkillsUnlocked.includes(node)) base.summary.newSkillsUnlocked.push(node);
  }
  for (const id of input.droppedEquipmentIds) {
    const item = ITEM_CATALOG[id];
    if (item && !base.summary.equipmentAcquired.some((it) => it.id === item.id)) {
      base.summary.equipmentAcquired.push(item);
    }
  }

  const vc = input.profileAfterCompletion?.virtualCharacter;
  base.snapshot = {
    level: getLevelFromXp(input.profileXpAfterCompletion),
    stats: {
      str: vc?.str ?? 0,
      int: vc?.int ?? 0,
      agi: vc?.agi ?? 0,
      cha: vc?.cha ?? 0,
      con: vc?.con ?? 0
    },
    equipment: {
      weapon: vc?.equipment.weapon?.name,
      armor: vc?.equipment.armor?.name,
      accessory: vc?.equipment.accessory?.name
    }
  };
  base.journal.mood = inferMood(base.summary);
  base.journal.autoGenerated = generateDailyJournal(base);
  await putDailyLog(base);
}

export async function appendDailyCheckIn(input: {
  completedAt: string;
  taskId: string;
  checkIn?: TaskCompletionCheckIn;
}): Promise<void> {
  if (!input.checkIn) return;
  const date = ymd(input.completedAt);
  const next = await getDailyLogByDate(date);
  if (!next) return;
  const ts = Date.now();
  if (input.checkIn.text?.trim()) {
    next.checkIns.push({
      taskId: input.taskId,
      type: "text",
      content: input.checkIn.text.trim(),
      timestamp: ts
    });
  }
  for (const image of input.checkIn.images ?? []) {
    next.checkIns.push({
      taskId: input.taskId,
      type: "image",
      content: image,
      timestamp: ts
    });
  }
  if (input.checkIn.voice) {
    next.checkIns.push({
      taskId: input.taskId,
      type: "voice",
      content: input.checkIn.voice,
      timestamp: ts
    });
  }
  await putDailyLog(next);
}

export async function sealDailyJournal(date: string): Promise<DailyLog | null> {
  const log = await getDailyLogByDate(date);
  if (!log || log.summary.totalTasks <= 0) return null;
  log.journal.mood = inferMood(log.summary);
  log.journal.autoGenerated = generateDailyJournal(log);
  await putDailyLog(log);
  return log;
}

export async function sealTodayJournal(): Promise<DailyLog | null> {
  const today = new Date().toISOString().slice(0, 10);
  return sealDailyJournal(today);
}

export async function compressOldLogsToMonthlySummary(): Promise<void> {
  const logs = await listDailyLogs();
  const now = Date.now();
  const cutoffMs = now - 90 * 24 * 3600 * 1000;
  for (const log of logs) {
    const t = new Date(`${log.date}T00:00:00`).getTime();
    if (t >= cutoffMs) continue;
    const month = monthOf(log.date);
    const prev = (await getMonthlySummary(month)) ?? {
      month,
      totalTasks: 0,
      totalXP: 0,
      totalCrystals: 0,
      days: 0
    };
    prev.totalTasks += log.summary.totalTasks;
    prev.totalXP += log.summary.totalXP;
    prev.totalCrystals += log.summary.totalCrystals;
    prev.days += 1;
    await putMonthlySummary(prev);
    await deleteDailyLog(log.date);
  }
}

export function scheduleDailySeal(onGenerated?: (log: DailyLog) => void): () => void {
  let timer: number | null = null;
  const arm = () => {
    const now = new Date();
    const next = new Date(now);
    next.setHours(23, 59, 0, 0);
    if (next.getTime() <= now.getTime()) {
      next.setDate(next.getDate() + 1);
      next.setHours(23, 59, 0, 0);
    }
    const delay = Math.max(1000, next.getTime() - now.getTime());
    timer = window.setTimeout(async () => {
      const log = await sealTodayJournal();
      if (log && onGenerated) onGenerated(log);
      await compressOldLogsToMonthlySummary();
      arm();
    }, delay);
  };
  arm();
  return () => {
    if (timer) {
      window.clearTimeout(timer);
      timer = null;
    }
  };
}

