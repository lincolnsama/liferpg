function ymd(iso: string): string {
  return iso.slice(0, 10);
}

function monthOf(date: string): string {
  return date.slice(0, 7);
}

function openJournalDb(): Promise<IDBDatabase> {
  return new Promise((resolve, reject) => {
    const req = indexedDB.open(DB_NAME, DB_VERSION);
    req.onupgradeneeded = () => {
      const db = req.result;
      if (!db.objectStoreNames.contains(DAILY_STORE)) {
        const store = db.createObjectStore(DAILY_STORE, { keyPath: "date" });
        store.createIndex("date", "date", { unique: true });
      }
      if (!db.objectStoreNames.contains(MONTHLY_STORE)) {
        db.createObjectStore(MONTHLY_STORE, { keyPath: "month" });
      }
      if (!db.objectStoreNames.contains(SEALS_STORE)) {
        db.createObjectStore(SEALS_STORE, { keyPath: "date" });
      }
    };
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

async function withStore<T>(
  storeName: string,
  mode: IDBTransactionMode,
  run: (store: IDBObjectStore) => Promise<T> | T
): Promise<T> {
  const db = await openJournalDb();
  return new Promise<T>((resolve, reject) => {
    const tx = db.transaction(storeName, mode);
    const store = tx.objectStore(storeName);
    let out!: T;
    tx.onerror = () => reject(tx.error);
    tx.onabort = () => reject(tx.error);
    tx.oncomplete = () => resolve(out);
    Promise.resolve(run(store))
      .then((val) => {
        out = val;
      })
      .catch(reject);
  });
}

function reqToPromise<T>(req: IDBRequest<T>): Promise<T> {
  return new Promise((resolve, reject) => {
    req.onsuccess = () => resolve(req.result);
    req.onerror = () => reject(req.error);
  });
}

export async function listDailyLogs(): Promise<DailyLog[]> {
  await migrateLegacyLocalStorageIfNeeded();
  return withStore(DAILY_STORE, "readonly", async (store) => {
    const rows = await reqToPromise(store.getAll() as IDBRequest<DailyLog[]>);
    return rows.sort((a, b) => (a.date > b.date ? -1 : 1));
  });
}

async function getDailyLogByDate(date: string): Promise<DailyLog | undefined> {
  return withStore(DAILY_STORE, "readonly", async (store) => {
    const row = await reqToPromise(store.get(date) as IDBRequest<DailyLog | undefined>);
    return row;
  });
}

async function putDailyLog(log: DailyLog): Promise<void> {
  await withStore(DAILY_STORE, "readwrite", async (store) => {
    store.put(log);
  });
}

async function deleteDailyLog(date: string): Promise<void> {
  await withStore(DAILY_STORE, "readwrite", async (store) => {
    store.delete(date);
  });
}

